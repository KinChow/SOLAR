"""Generate the full SOLAR model contract from simplified user input."""

import ast
from pathlib import Path
from typing import List

from solar_web.api.schemas import RunCreateRequest


class InputContractError(ValueError):
    """Raised when submitted code does not match the demo input contract."""


class ModelFileBuilder:
    def build(self, request: RunCreateRequest, output: Path) -> Path:
        tree = self._parse(request.operator_code)
        self._validate(tree, [tensor.name for tensor in request.inputs])
        source = self._render(request)
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(source)
        return output

    @staticmethod
    def _parse(source: str) -> ast.Module:
        try:
            return ast.parse(source)
        except SyntaxError as error:
            raise InputContractError(f"invalid Python syntax: {error.msg}") from error

    @staticmethod
    def _validate(tree: ast.Module, input_names: List[str]) -> None:
        if any(isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name in {"get_inputs", "get_init_inputs"} for node in tree.body):
            raise InputContractError("get_inputs/get_init_inputs are generated by the Web demo")
        model = next((node for node in tree.body if isinstance(node, ast.ClassDef) and node.name == "Model"), None)
        if model is None:
            raise InputContractError("operator code must define class Model")
        methods = {node.name: node for node in model.body if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))}
        forward = methods.get("forward")
        if forward is None or isinstance(forward, ast.AsyncFunctionDef):
            raise InputContractError("Model must define a synchronous forward method")
        if forward.args.vararg or forward.args.kwarg or forward.args.kwonlyargs:
            raise InputContractError("forward must use explicit positional tensor arguments")
        positional = list(forward.args.posonlyargs) + list(forward.args.args)
        forward_names = [argument.arg for argument in positional if argument.arg != "self"]
        if forward_names != input_names:
            raise InputContractError(
                f"forward arguments {forward_names} do not match tensor inputs {input_names}"
            )
        initializer = methods.get("__init__")
        if initializer is not None:
            init_positional = list(initializer.args.posonlyargs) + list(initializer.args.args)
            if [argument.arg for argument in init_positional if argument.arg != "self"]:
                raise InputContractError("Model constructor must not require arguments")

    @staticmethod
    def _render(request: RunCreateRequest) -> str:
        tensors = ",\n        ".join(
            f"torch.randn({tuple(tensor.shape)!r}, dtype=torch.{tensor.dtype})"
            for tensor in request.inputs
        )
        return (
            "import torch\n"
            "from torch import nn\n\n"
            f"{request.operator_code.strip()}\n\n"
            "def get_inputs():\n"
            "    torch.manual_seed(0)\n"
            "    return [\n"
            f"        {tensors}\n"
            "    ]\n\n"
            "def get_init_inputs():\n"
            "    return []\n"
        )
